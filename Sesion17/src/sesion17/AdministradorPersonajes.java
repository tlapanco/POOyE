    private void cargarInfoInicial() {
        cbTipoPersonaje.setModel(new DefaultComboBoxModel<TipoPersonaje>(TipoPersonaje.values()));
        cbTipoElemento.setModel(new DefaultComboBoxModel<Elemento>(Elemento.values()));
        cbCreadores.addItem(new Creador("Selecciona", "un creador"));
        txtIdCreador.setText(String.valueOf(Creador.getSiguienteId()));

    }

    private String buscarCreador(int id) {

        for (Creador c : creadores) {
            if (c.getIdCreador() == id) {
                return c.toString();
            }
        }

        return "Desconocido";
    }

    private void cargarPersonajes() {

        DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

        modelo.setRowCount(0); // 🔥 limpia la tabla

        for (Personaje p : personajes) {

            modelo.addRow(new Object[]{
                p.getNombre(),
                p.getApodo(),
                p.getElemento(),
                p.getTipo(),
                buscarCreador(p.getIdCreador())
            });
        }
    }

