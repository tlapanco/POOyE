    private void btnAddCreadorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddCreadorActionPerformed
        //Validar info
        if (txtNombreCreador.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nombre no puede estar vacío");
            return;
        }
        if (txtApellidosCreador.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo apellidos no puede estar vacío");
            return;
        }

        Creador nuevoCreador = new Creador(txtNombreCreador.getText(), txtApellidosCreador.getText());
        creadores.add(nuevoCreador);
        cbCreadores.addItem(nuevoCreador);
        txtIdCreador.setText(String.valueOf(Creador.getSiguienteId()));

        //Limpiar campos de texto
        txtApellidosCreador.setText("");
        txtNombreCreador.setText("");

        JOptionPane.showMessageDialog(this, "Creador agregado correctamente");
    }//GEN-LAST:event_btnAddCreadorActionPerformed

    private void btnAddPersonajeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddPersonajeActionPerformed
        if (cbTipoElemento.getSelectedItem() == Elemento.SELECCIONAR) {
            JOptionPane.showMessageDialog(this, "Selecciona un elemento");
            return;
        }
        if (cbTipoPersonaje.getSelectedItem() == TipoPersonaje.SELECCIONAR) {
            JOptionPane.showMessageDialog(this, "Selecciona un tipo de personaje");
            return;
        }
        if (cbCreadores.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Selecciona un creador");
            return;
        }

        if (txtNombrePersonaje.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Nombre no puede estar vacío");
            return;
        }

        if (txtApodoPersonaje.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El campo Apodo no puede estar vacío");
            return;
        }
        Creador creadorDelPersonaje = (Creador) cbCreadores.getSelectedItem();

        Personaje nuevoPersonaje = new Personaje(
                txtNombrePersonaje.getText(),
                (Elemento) cbTipoElemento.getSelectedItem(),
                "sfds",
                txtApodoPersonaje.getText(),
                (TipoPersonaje) cbTipoPersonaje.getSelectedItem(),
                creadorDelPersonaje.getIdCreador());

        personajes.add(nuevoPersonaje);

        txtNombrePersonaje.setText("");
        txtApodoPersonaje.setText("");
        cbCreadores.setSelectedIndex(0);
        cbTipoElemento.setSelectedIndex(0);
        cbTipoPersonaje.setSelectedIndex(0);

        cargarPersonajes();
        JOptionPane.showMessageDialog(this, "Personaje agregado correctamente");

    }//GEN-LAST:event_btnAddPersonajeActionPerformed

